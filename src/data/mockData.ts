export function generateSeedAttendanceRecords(): AttendanceRecord[] {
  const records: AttendanceRecord[] = [];
  const now = new Date();

  INITIAL_COURSES.forEach((course) => {
    for (let i = 1; i <= course.totalLecturesConducted; i++) {
      const lectureDate = new Date(now.getTime() - (course.totalLecturesConducted - i) * 2.2 * 24 * 60 * 60 * 1000);
      const sessionId = `sess_${course.id}_${i}`;

      ALL_STUDENTS_ROSTER.forEach((student) => {
        let status: 'PRESENT' | 'ABSENT' | 'LEAVE' = 'PRESENT';

        if (SAFE_STUDENT_IDS.has(student.id)) {
          // Safe student: ~88-92% attendance (absent on only lecture 4 or 18)
          if (i === 4 || i === 18) {
            status = 'ABSENT';
          }
        } else if (RISK_STUDENT_IDS.has(student.id)) {
          // At-risk student: ~60-64% attendance (absent on many lectures)
          if (i % 3 === 0 || i === 2 || i === 7 || i === 13 || i === 19 || i === 23) {
            status = 'ABSENT';
          }
        } else {
          const hash = (student.roll.charCodeAt(student.roll.length - 1) + i * 17) % 100;
          if (hash < 14) status = 'ABSENT';
          else if (hash < 18) status = 'LEAVE';
        }

        records.push({
          id: `att_${sessionId}_${student.id}`,
          sessionId,
          courseId: course.id,
          studentId: student.id,
          studentName: student.name,
          studentRoll: student.roll,
          timestamp: lectureDate.toISOString(),
          status,
          verificationMethod: status === 'PRESENT' ? 'qr_dynamic' : 'roll_call',
          deviceInfo: 'LJ University Portal v3.0',
          locationVerified: true,
        });
      });
    }
  });

  return records;
}
